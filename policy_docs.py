def days_between(d1, d2):
    """d1 -> d2 间隔天数，格式 YYYY-MM-DD"""
    y1, m1, dd1 = map(int, d1.split("-"))
    y2, m2, dd2 = map(int, d2.split("-"))
    return (date(y2, m2, dd2) - date(y1, m1, dd1)).days
